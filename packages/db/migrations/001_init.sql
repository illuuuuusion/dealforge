-- Initial PostgreSQL schema (replaces the SQLite prototype). Money as numeric(10,2), never float.
CREATE TABLE watchlists (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  query text NOT NULL,
  max_working numeric(10,2) NOT NULL,
  max_defect numeric(10,2) NOT NULL,
  expected_resale numeric(10,2),
  repair_budget numeric(10,2) NOT NULL DEFAULT 0,
  sources text[] NOT NULL,
  allow_unknown_shipping boolean NOT NULL DEFAULT false,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX watchlists_active ON watchlists (active);

-- Timestamps: published_at = source's own listing time (NULL if unknown, never invented),
-- first_seen_at / last_seen_at = our ingest time, fetched_at = when the provider response was received.
CREATE TABLE listings (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source text NOT NULL CHECK (source IN ('ebay', 'kleinanzeigen', 'facebook')),
  external_id text NOT NULL,
  title text NOT NULL,
  description text,
  url text NOT NULL,
  image_url text,
  price_eur numeric(10,2) NOT NULL,
  shipping_eur numeric(10,2),
  condition text,
  offer_type text NOT NULL DEFAULT 'FIXED_PRICE' CHECK (offer_type IN ('FIXED_PRICE', 'AUCTION', 'OTHER')),
  auction_ends_at timestamptz,
  bid_count integer,
  published_at timestamptz,
  first_seen_at timestamptz NOT NULL,
  last_seen_at timestamptz NOT NULL,
  fetched_at timestamptz NOT NULL,
  health text NOT NULL,
  model_key text,
  status text NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'saved', 'dismissed', 'contacted', 'purchased')),
  UNIQUE (source, external_id)
);
CREATE INDEX listings_first_seen ON listings (first_seen_at DESC);
CREATE INDEX listings_model_health ON listings (model_key, health);

-- One row per observed change of price/shipping/title/condition; identical replays add nothing.
CREATE TABLE listing_snapshots (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  listing_id integer NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
  observed_at timestamptz NOT NULL,
  price_eur numeric(10,2) NOT NULL,
  shipping_eur numeric(10,2),
  title_hash text,
  condition_hash text
);
CREATE INDEX listing_snapshots_latest ON listing_snapshots (listing_id, observed_at DESC, id DESC);

CREATE TABLE watchlist_matches (
  listing_id integer NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
  watchlist_id integer NOT NULL REFERENCES watchlists(id) ON DELETE CASCADE,
  evaluation_version integer NOT NULL,
  assessment jsonb NOT NULL,
  matched_at timestamptz NOT NULL,
  PRIMARY KEY (listing_id, watchlist_id)
);
CREATE INDEX watchlist_matches_watchlist ON watchlist_matches (watchlist_id);

CREATE TABLE source_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source text NOT NULL,
  query_key text,
  started_at timestamptz NOT NULL,
  finished_at timestamptz NOT NULL,
  status text NOT NULL CHECK (status IN ('ok', 'error', 'skipped')),
  http_status integer,
  fetched integer NOT NULL DEFAULT 0,
  inserted integer NOT NULL DEFAULT 0,
  error_code text,
  message text
);
CREATE INDEX source_runs_recent ON source_runs (source, started_at DESC);

-- Budget ledger: one counter per provider, search filter and UTC day. Reserved before every request.
CREATE TABLE provider_usage (
  provider text NOT NULL,
  query_key text NOT NULL,
  day date NOT NULL,
  calls integer NOT NULL DEFAULT 0,
  PRIMARY KEY (provider, day, query_key)
);

-- Runtime kill switch per provider; APPROVED_PROVIDERS still gates what may ever go live.
CREATE TABLE provider_flags (
  source text PRIMARY KEY,
  enabled boolean NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);
