-- One personal repair case per listing. Title/URL are copied so the project outlives the listing.
CREATE TABLE repair_projects (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  listing_id integer UNIQUE REFERENCES listings(id) ON DELETE SET NULL,
  title text NOT NULL,
  url text,
  model text,
  faults text[] NOT NULL,
  status text NOT NULL DEFAULT 'candidate' CHECK (status IN ('candidate', 'purchased', 'repairing', 'repaired', 'sold', 'abandoned')),
  outcome text NOT NULL DEFAULT 'open' CHECK (outcome IN ('open', 'success', 'partial', 'failed')),
  purchase_price numeric(10,2) NOT NULL,
  purchase_shipping numeric(10,2),
  purchased_at date,
  parts jsonb NOT NULL DEFAULT '[]',
  hours_spent numeric(6,2) NOT NULL DEFAULT 0,
  resale_estimate numeric(10,2),
  salvage_estimate numeric(10,2) NOT NULL DEFAULT 0,
  sold_price numeric(10,2),
  sold_fees numeric(10,2),
  sold_shipping numeric(10,2),
  sold_at date,
  notes text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX repair_projects_recent ON repair_projects (created_at DESC);
