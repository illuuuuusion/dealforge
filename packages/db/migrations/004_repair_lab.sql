-- Repair Lab: own cost assumptions and repair projects. Single user: exactly one settings row.
CREATE TABLE repair_settings (
  id boolean PRIMARY KEY DEFAULT true CHECK (id),
  hourly_rate numeric(10,2) NOT NULL,
  sale_fee_pct numeric(5,2) NOT NULL,
  resale_shipping numeric(10,2) NOT NULL
);
