-- Parts and time ranges per fault class; model '' = default, a row with the exact model overrides it.
CREATE TABLE repair_costs (
  fault text NOT NULL CHECK (fault IN ('NO_DISPLAY', 'ARTIFACTS', 'DRIVER_CRASH', 'NO_POWER', 'WATER_DAMAGE', 'BURN_DAMAGE', 'PARTS_MISSING', 'UNKNOWN')),
  model text NOT NULL DEFAULT '',
  parts_min numeric(10,2) NOT NULL,
  parts_max numeric(10,2) NOT NULL CHECK (parts_max >= parts_min),
  hours_min numeric(6,2) NOT NULL,
  hours_max numeric(6,2) NOT NULL CHECK (hours_max >= hours_min),
  PRIMARY KEY (fault, model)
);
