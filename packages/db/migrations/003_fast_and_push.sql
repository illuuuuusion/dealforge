-- Fast watchlists are polled on their own, shorter schedule (only sources in FAST_PROVIDERS; budgets still apply).
ALTER TABLE watchlists ADD COLUMN fast boolean NOT NULL DEFAULT false;

-- Provider response time of the batch that raised the alert: start of the in-app latency chain (DF-308).
ALTER TABLE alerts ADD COLUMN fetched_at timestamptz;

-- Generated once and shared by API and worker (e.g. the VAPID key pair).
CREATE TABLE app_secrets (
  name text PRIMARY KEY,
  value text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- ponytail: endpoint and keys stored in plain text, single user; encrypt with the other secrets once multi-user.
CREATE TABLE push_subscriptions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  endpoint text NOT NULL UNIQUE,
  p256dh text NOT NULL,
  auth text NOT NULL,
  user_agent text,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_success_at timestamptz
);

-- Delivery log (DF-307): pending -> sent (accepted by the push service) | failed | gone (subscription expired).
-- shown_at only comes from a receipt of the service worker, never assumed. alert_id NULL = test push.
CREATE TABLE alert_deliveries (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  alert_id bigint REFERENCES alerts(id) ON DELETE CASCADE,
  subscription_id integer REFERENCES push_subscriptions(id) ON DELETE SET NULL,
  status text NOT NULL CHECK (status IN ('pending', 'sent', 'failed', 'gone')),
  http_status integer,
  error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  sent_at timestamptz,
  shown_at timestamptz,
  UNIQUE (alert_id, subscription_id)
);
CREATE INDEX alert_deliveries_recent ON alert_deliveries (created_at DESC);
